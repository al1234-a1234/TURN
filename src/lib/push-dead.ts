/**
 * متى يكون اشتراك الدفع ميّتًا لا رجعة فيه؟
 *
 * مُستخرَجٌ من `push.ts` وحده — بلا `server-only` وبلا `web-push` — كي يصير
 * قابلًا للاختبار. القرار هنا يحذف صفًّا من قاعدة الإنتاج، وقاعدةٌ تحذف
 * بيانات ولا اختبار عليها هي بالضبط ما نطارده.
 *
 * ── القاعدة ──
 * `404/410` هما الميتة المعلنة: أُلغي التصريح أو حُذف التطبيق.
 *
 * وأُضيف إليهما `VapidPkHashMismatch`: جهازٌ اشترك بمفتاح VAPID قديم، فترفض
 * آبل توقيعنا بالمفتاح الجديد — رفضًا **دائمًا** لا عارضًا. وترجعه بـ`400`،
 * فكان يفلت من التنظيف: اثنا عشر رفضًا متتاليًا في الإنتاج بين ٢٧ و٢٩ أغسطس
 * ٢٠٢٦ على صفٍّ واحد، والعميل يرى «التنبيه مفعّل» ولا يصله شيء.
 *
 * ── ولماذا المِعيار نصُّ السبب لا الرمز `400` ──
 * الأربعمئة سلّةُ «طلبٌ خاطئ»: حمولةٌ فاسدة أو رأسٌ ناقص يقعان فيها أيضًا.
 * فحذفُ كلّ `400` يعني أنّ خطأً واحدًا عندنا يمسح اشتراكات المنصّة كلّها في
 * دفعةٍ واحدة — عطبٌ أسوأ من الذي نُصلحه. النصّ يخصّ المفتاح وحده.
 *
 * (لجوجل صياغةٌ مقابلة لهذه الحالة لم تظهر لنا في الإنتاج قطّ — ولا نحذف على
 *  صياغةٍ لم نرها. تُضاف يوم يظهر سطرها في `notifications`.)
 */
export function isDeadSubscription(code: number | undefined, body: string): boolean {
  if (code === 404 || code === 410) return true;
  return body.includes("VapidPkHashMismatch");
}
