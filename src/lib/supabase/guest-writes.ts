/**
 * قلمُ الضيف — العميل الذي تُكتب به أفعال الضيف على القاعدة.
 *
 * المشكلة التي يحلّها: مفتاح `anon` علنيٌّ بحكم التعريف — يُشحن في حزمة
 * المتصفّح، ومن فتح الصفحة يملكه. وكانت دوالّ الكتابة (الانضمام، الحجز،
 * الإلغاء، التقييم) ممنوحةً له، فكان أيّ أحدٍ ينادي PostgREST مباشرةً بلا
 * مرورٍ بخادمنا. وسقوفُ القاعدة تحدّ الضرر ولا تمنع المحاولة: الحدّ ثلاثة
 * انضماماتٍ لكلّ رقم، والمهاجم يملك أرقامًا بلا حدّ.
 *
 * وكلّ حارسٍ بنيناه في الخادم — حدّ العنوان، تطبيع الرقم، قصّ القسم، سقف
 * الحجم — كان يُتخطّى بنداءٍ واحدٍ يتجاوز الخادم. حارسٌ يُلتفّ حوله ليس
 * حارسًا، بل شعورٌ بالأمان.
 *
 * فالكتابة تمرّ من هنا بمفتاح الخدمة، ثم تُسحب الدوالّ من `anon` (0093).
 * ولا توسّع في الصلاحية بهذا: الدوالّ كلّها `SECURITY DEFINER` أصلًا، أي
 * أنّها تعمل بصلاحية مالكها لا بصلاحية مستدعيها منذ اليوم الأول. المتغيّر
 * الوحيد: من يُسمح له بطرق الباب.
 *
 * وإن غاب مفتاح الخدمة يرجع إلى عميل الطلب بدل أن يرمي — نشرةٌ ناقصة
 * الإعداد يجب أن تُبطئ لا أن تُسقط الطابور. وهذا الرجوع يعمل ما دامت
 * الصلاحية لم تُسحب بعد؛ وبعد سحبها يصير غيابُ المفتاح عطلًا صريحًا،
 * وهو الصواب: الصمت أسوأ من الصوت.
 *
 * ولا يُستعمل للقراءة العامّة: القراءة تبقى بعميل الطلب لتظلّ سياسات
 * الصفوف عاملةً عليها. مفتاح الخدمة يتجاوز RLS كلَّه، فكلّ استعمالٍ له
 * خارج ما كُتب هنا توسيعٌ صامتٌ لسطح الخطر.
 */
export async function guestWriter() {
  return createAdminClient() ?? (await createRequestClient());
}
