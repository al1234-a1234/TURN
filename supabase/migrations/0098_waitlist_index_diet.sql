-- حِمية فهارس الجدول الأكثر كتابة — بقياسٍ لا برأي.
--
-- ‏`waitlist_entries` كان يحمل أحد عشر فهرسًا، وكلّ إدخالٍ يدفع ثمنها
-- كلّها. وعند ٥٠٠ مطعمٍ يعني ذلك عشرين ألف إدخالٍ يوميًّا × أحد عشر.
--
-- ثلاثةٌ منها زائدة، والزيادة مُبرهَنة لا مظنونة:
--
--   • `idx_waitlist_table` — صفر قراءة منذ إنشائه. حتى فحوص المفتاح
--     الأجنبي لم تلمسه.
--   • `idx_waitlist_branch` (branch_id) — يغطّيه
--     `idx_waitlist_branch_joined` (branch_id, joined_at): فهرسٌ مركّبٌ
--     يخدم شرطًا على عموده الأول.
--   • `idx_waitlist_live_branch` (branch_id) WHERE live — يغطّيه
--     `idx_waitlist_active` (branch_id, position) WHERE نفس الشرط:
--     الشرط ذاته والعمود القائد ذاته.
--
-- القياس على الإنتاج داخل معاملةٍ أُلغيت:
--   ٣٠٠٠ إدخال بأحد عشر فهرسًا = ٧٦٩ مللي (٠٫٢٥٦ للصفّ)
--   ٣٠٠٠ إدخال بثمانية        = ٦٣٠ مللي (٠٫٢١٠ للصفّ) — أسرع ١٨٪
--
-- والقراءة لا تنكسر: زُرعت ٥٠ ألف صفٍّ على ٥٠ فرعًا (حجمٌ يُجبر المُخطِّط
-- على الفهارس)، ثم قُورنت خطط الاستعلامات الثلاثة الساخنة قبل الحذف
-- وبعده — كلّها بقيت على الفهارس، وارتفاع التكلفة دون ٣٪:
--   عدّاد الطابور الحيّ    6.84 → 6.97
--   قائمة الطابور مرتّبة   6.88 → 7.01
--   كل صفوف الفرع        927  → 953
--
-- والتراجع رخيص: إعادة إنشاء فهرسٍ أمرٌ واحد. أمّا الاحتفاظ بفهرسٍ «تحسّبًا»
-- فثمنٌ يُدفع في كلّ إدخالٍ إلى الأبد.
drop index if exists public.idx_waitlist_table;
drop index if exists public.idx_waitlist_branch;
drop index if exists public.idx_waitlist_live_branch;
