-- القائمة تتكلّم لغتَي التطبيق — كانت الوحيدة التي لا تفعل.
--
-- كشفتها بروفةُ الخمسة والعشرين: جهّزتُ مطعمًا كاملًا كأنّي مالكه، فوجدت
-- أنّ `menu_categories` و`menu_items` فيهما `name` وحده. والمطعم والفرع
-- والقسم كلّها ثنائية (`name_en`).
--
-- فالعميل الذي يبدّل اللغة يقرأ واجهةً إنجليزية كاملة — الأزرار والحالة
-- ورسائل الخطأ — ثم يصل إلى القائمة فيجدها عربيّة. وهي الشاشة التي جاء
-- لأجلها. وتفاوتٌ كهذا لا يُقرأ «ميزةٌ ناقصة» بل «منتجٌ غير مكتمل».
--
-- والحقول اختيارية عمدًا: مطعمٌ لا يريد ترجمة قائمته لا يُجبَر، والعرض
-- يرجع إلى العربية عند غياب الترجمة — لا إلى فراغ. فالنقص يظهر صنفًا
-- صنفًا لا دفعةً واحدة، ويملؤه المالك على مهله.
alter table public.menu_categories add column if not exists name_en text;
alter table public.menu_items      add column if not exists name_en text;
alter table public.menu_items      add column if not exists description_en text;
