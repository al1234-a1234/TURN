--  ث‑١ — التقييمات: تُكتب بدالّةٍ واحدةٍ محروسة، لا بالجدول مباشرةً
--
--  الحال قبل هذا الترحيل: دالّة submit_review تفرض أربعة حرّاس — حدّ ٥ تقييمات
--  لكلّ رقمٍ في ٢٤ ساعة، ووجود العميل، وزيارةً فعليّة (status='seated' خلال
--  ٧ أيّام)، وتقييمًا واحدًا لكلّ (مطعم، عميل) تُحدِّثه ولا تكرّره.
--  والجدول نفسه لا يفرض أيًّا منها: سياسة «customer writes own review» تشترط
--  أن يكون customer_id لك فحسب، وسياسة «customer inserts self» تتيح لك إنشاء
--  صفّ customers لنفسك. فأيّ حسابٍ مسجَّل يكتب ما شاء من التقييمات لأيّ مطعم،
--  و is_published قيمتها الافتراضيّة true فتظهر فورًا.
--  ثبت عمليًّا: ٢٠٠ تقييمٍ بنجمةٍ واحدة لمطعمٍ لم يزره الفاعل قطّ — نجحت،
--  ثمّ ١٠٠٠ دفعةً واحدة — نجحت. القيد الوحيد العامل كان مدى النجوم.
--
--  الأثر: نجمةُ صفحة المطعم العامّة — وهي كلّ ثقة المطعم عند الزبون — قابلةٌ
--  للهدم أو التلميع من حسابٍ واحد. ولذلك يُغلَق الباب لا يُضيَّق:
--  يُسحب INSERT من anon و authenticated، فيبقى الطريق الوحيد submit_review،
--  وهي SECURITY DEFINER تعمل بصلاحيّة مالكها فلا يمسّها السحب.
--
--  ويُضاف فهرسٌ فريد يجعل قاعدة «تقييمٌ واحدٌ لكلّ عميلٍ لكلّ مطعم» قيدًا في
--  القاعدة لا سطرًا في دالّة — يصمد لأيّ مسارٍ قادم، ولمفتاح الخدمة نفسه.
-- ════════════════════════════════════════════════════════════════════════════

-- ── ١) البيانات المبذورة تُزال قبل الفهرس ──────────────────────────────────
--
-- التقييمات الـ٦٦ كلّها من هويّاتٍ مولَّدة («زائر ١..٢٦» وأرقام 0552000/05770)،
-- وفيها تكرارٌ لنفس (مطعم، عميل) يُسقط الفهرس الفريد لو بقي. وهي تصنع أيضًا
-- نجمة ★٤٫٤ المعروضة اليوم على صفحةٍ عامّة — رقمٌ لا يقابله زبونٌ واحد.
--
-- النطاق: الهويّات المولَّدة وحدها. صفوف الأشخاص الحقيقيّين الذين جرّبوا
-- التطبيق بأيديهم تبقى — تلك تجارب، لا بذور.
--
-- الترتيب يفرضه القيد المرجعيّ: reservations و waitlist_entries تشيران إلى
-- customers بـRESTRICT، فتُحذف قبلها. و customer_restaurant و customer_rewards
-- و push_subscriptions تنحذف تلقائيًّا بـCASCADE.

-- المرشّح مكرَّرٌ في الجمل الأربع عمدًا: جدولٌ مؤقّتٌ وسيطٌ يجعل الترحيل
-- يعتمد على عمر الجلسة، والتكرار هنا أصدق وأقصر من الاعتماد عليه.

delete from public.reviews where customer_id in (
  select id from public.customers where phone ~ '^05(52000|5770)' or phone ~ '^059000');

delete from public.reservations where customer_id in (
  select id from public.customers where phone ~ '^05(52000|5770)' or phone ~ '^059000');

delete from public.waitlist_entries where customer_id in (
  select id from public.customers where phone ~ '^05(52000|5770)' or phone ~ '^059000');

delete from public.customers
  where phone ~ '^05(52000|5770)' or phone ~ '^059000';

-- ── ٢) تقييمٌ واحدٌ لكلّ عميلٍ لكلّ مطعم — قيدًا لا عُرفًا ──────────────────
--
-- submit_review تُحدِّث الصفّ القائم بدل أن تُدخل ثانيًا، فالفهرس لا يعطّلها.
-- الصفوف بلا عميل (customer_id is null) خارج القيد: لا هويّة تُكرَّر فيها.

create unique index if not exists uniq_review_per_customer_restaurant
  on public.reviews (restaurant_id, customer_id)
  where customer_id is not null;

-- ── ٣) سحب الإدخال المباشر ────────────────────────────────────────────────
--
-- السياسة تُحذف والصلاحيّة تُسحب معًا: السياسة وحدها لا تكفي لأنّ صلاحيّة
-- الجدول باقية، والسحب وحده يترك سياسةً ميّتة تُوهم القارئ أنّ الباب مفتوح.

drop policy if exists "customer writes own review" on public.reviews;

revoke insert on public.reviews from anon, authenticated;

