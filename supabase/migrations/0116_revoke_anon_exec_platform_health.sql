-- ٠١١٦ — تصحيح ٠١١٥: نفس نمط ٠١١١/٠١١٢، اكتُشف الآن أنه سيتكرّر مع كل دالّةٍ جديدة
--
-- proacl لـcheck_platform_health بعد ٠١١٥ أظهر anon=X صريحةً رغم
-- `revoke ... from public` في نفس الترحيل — تمامًا كما حدث مع الثلاث عشرة
-- دالّةً في ٠١١١. هذا يؤكّد أن المشروع يحمل على الأرجح
-- `alter default privileges in schema public grant execute on functions
-- to anon, authenticated` (أو ما يعادله) — فكل دالّةٍ جديدة تُنشأ في
-- public تُمنح EXECUTE لـanon تلقائيًّا وقت الإنشاء، بصرف النظر عمّا
-- يُكتب بعدها في نفس الترحيل من `revoke ... from public`.
--
-- الإصلاح النطاقي (سحبٌ صريح لكل دالّةٍ بعد إنشائها) هو نفس نهج ٠١١١-٠١١٤،
-- ومتعمَّدٌ أن يبقى نطاقيًّا لا جذريًّا: تعديل default privileges على
-- مستوى السكيما كاملةً يمسّ السبع دوالٍّ المكشوفة للضيف عمدًا أيضًا (على
-- الأرجح مُنحت anon بنفس الآلية) وقد يكسرها بلا اختبارٍ فرديٍّ لكل واحدة
-- — خطرٌ لا مبرّر له في جلسةٍ ليليةٍ قبل تسليم. يُترك للتقرير النهائي
-- كبندٍ يستحق مراجعةً متأنّية في جلسةٍ مخصَّصة.

revoke execute on function public.check_platform_health() from anon;
