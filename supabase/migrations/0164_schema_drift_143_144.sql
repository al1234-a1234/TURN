-- ============================================================================
--  q20_schema_no_drift: تحديث بصمة الدوالّ ١٤٣ ← ١٤٤ — إتمامٌ لما نقص في 0161.
--
--  ── ما وقع بالضبط، لا تخمينًا ──
--  طُبِّقت أربعة ترحيلاتٍ متتابعة على الإنتاج (0160 → 0163). و0161 أضاف دالّةً
--  جديدة (`clear_confirmed_on_no_show`، محفّزُ مسح تأكيد الحضور) **بلا أن
--  يحرّك بصمة الانحراف معه** — وهذا سهوٌ في 0161 نفسه، لا في الفحص.
--  و0163 كان يرفع البصمة بفارقٍ حسابيّ (`+١` جدول و`+١` دالّة) مقصودٍ
--  لنفسه وحده، لأنّ ثلاثة PRs كانت معلّقةً وقد تُدمج بأيّ ترتيب. فالفارق
--  صحيحٌ لـ0163، لكنّه لا يعوّض سهو 0161.
--
--  الأرقام المقيسة على الإنتاج بعد 0163 مباشرةً:
--    جداول: ٣٣ فعليّة · ٣٣ متوقَّعة ✔
--    دوالّ: ١٤٤ فعليّة · ١٤٣ متوقَّعة ✘ ← الفارق واحدٌ بالضبط
--    سياسات ومفاتيح أجنبية: بلا تغيير
--
--  فالانحراف معروفُ المصدر ومحصورٌ في دالّةٍ واحدةٍ مقصودة. والفحص عمل كما
--  يجب: صرخ حين تحرّك المخطّط. فالواجب تحديث المرجع عمدًا وموثَّقًا — لا
--  إسكات الفحص ولا حذفه ولا تخفيف شرطه (الخطّ الأحمر الخامس في الميثاق).
--
--  ولا يُكتب الرقم بيدي: يُقرأ القائم ويُزاد واحدًا، بحارسٍ يتوقّف إن لم يجد
--  البصمة أو إن وجد الرقم متغيّرًا عمّا قِيس — فلا يمرّ انحرافٌ آخر مختبئًا
--  خلف هذا التصحيح.
-- ============================================================================

do $mig$
declare v_def text; v_funcs int; v_actual int;
begin
  select pg_get_functiondef(p.oid) into v_def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'run_critical_checks';
  if v_def is null then raise exception 'run_critical_checks غير موجودة — توقّف'; end if;

  v_funcs := (regexp_match(v_def, 'p\.prokind=''f''\) = (\d+)'))[1]::int;
  if v_funcs is null then
    raise exception 'لم أجد بصمة الدوالّ في q20 — راجع يدويًّا';
  end if;

  select count(*) into v_actual
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f';

  -- الحارس: الفارق واحدٌ لا أكثر. لو اتّسع فثمّة انحرافٌ آخر لا يخصّ 0161،
  -- ولا يجوز أن يمرّ في ثوب تصحيح.
  if v_actual - v_funcs <> 1 then
    raise exception 'الفارق المتوقَّع ١ (سهو 0161)، والموجود % (فعليّ % مقابل متوقَّع %) — توقّفٌ للمراجعة اليدويّة',
      v_actual - v_funcs, v_actual, v_funcs;
  end if;

  v_def := replace(v_def, 'p.prokind=''f'') = ' || v_funcs, 'p.prokind=''f'') = ' || (v_funcs + 1));
  execute v_def;
end
$mig$;

