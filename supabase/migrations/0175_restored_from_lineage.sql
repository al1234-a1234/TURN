-- 0175 — نسبُ الإرجاع: من أيّ صفٍّ نشأ هذا الصفّ
--
-- الخيار (ب) بقرار المالك: **احفظ النسب الآن، وأجّل قرار العدّ.**
--
-- المشكلة التي يحلّها هذا الملفّ ليست ازدواج العدّ — بل أنّ الدليل عليه
-- يتبخّر. `restore_queue_entry` يُنشئ صفًّا جديدًا ويترك الأصليّ بحالته،
-- والرابط بينهما يعيش اليوم في `queue_events.detail->>'restored_from'`
-- وحدها — و`prune_queue_events` **يحذف كلّ حدثٍ بعد ٣٠ يومًا**.
--
-- فبعد شهرٍ لا يبقى في القاعدة ما يقول إنّ هذين الصفّين ضيفٌ واحد. وحينها
-- لا الخيار (أ) ولا غيره قابلٌ للتطبيق رجعيًّا — يُفقَد الخيار نفسه لا
-- الفرصة فقط. فحفظ النسب اليوم يشتري وقت القرار مجّانًا.
--
-- ⚠️ **صفر أثرٍ على أيّ رقمٍ معروض.** لا حسبة تُلمس، ولا تقرير يقرأ هذا
--    العمود بعد. `/dashboard/reports` لا يعرف بوجوده أصلًا. الإثبات
--    رقميّ: كل مقياسٍ في التقارير قيس قبل وبعد، وطابق.

begin;

-- ═══════════════════════════════════════════════════════════════════
-- العمود — بلا مفتاحٍ خارجيّ، وهذا مقصود
-- ═══════════════════════════════════════════════════════════════════
-- سببان:
--
-- ١) الحذف من waitlist_entries واقعٌ متكرّر (admin_audit: ١٥٨٨ حذفًا في
--    ٢١ يومًا). ومفتاحٌ خارجيّ بـON DELETE SET NULL كان سيمحو النسب عند
--    حذف الأصل — أي يُفقدنا بالضبط ما جئنا نحفظه. والمعرّف الميّت شهادةٌ
--    أصدق من فراغ: يقول «كان هنا صفٌّ وحُذف».
--
-- ٢) وq20 يعدّ المفاتيح الخارجية. فإضافة مفتاحٍ كانت تُلزمنا برفع عدّاده،
--    وذلك تغييرٌ في مرجعٍ لا داعي له حين يكون البديل أسلم أصلًا. فبقيت
--    شبكة الفحوص بلا لمسةٍ واحدة: ٢١٣/٢١٣ قبل وبعد.
--
-- والثمن معروفٌ ومقبول: لا تضمن القاعدة أنّ المعرّف يشير إلى صفٍّ قائم.
-- وهو عمود نسبٍ للمراجعة لا مفتاح انضمامٍ في مسارٍ حيّ — فمن يقرؤه يقرؤه
-- بـLEFT JOIN ويحتمل الغياب.

alter table public.waitlist_entries
  add column if not exists restored_from uuid;

comment on column public.waitlist_entries.restored_from is
  'الصفّ الذي أُرجع عنه هذا الصفّ (restore_queue_entry). NULL للأغلبيّة '
  'الساحقة. للنسب والمراجعة فقط — لا تقرؤه أيّ حسبةٍ في التقارير بعد، '
  'وقرار احتساب الضيف مرّةً أو مرّتين لم يُتّخذ. بلا مفتاحٍ خارجيّ عمدًا: '
  'الأصل قد يُحذف، والمعرّف الميّت أصدق من فراغ.';

-- فهرسٌ جزئيّ: الصفوف ذات النسب نادرةٌ جدًّا (٩ من ٤٢٤ اليوم)، فالفهرس
-- الجزئيّ يخدم أيّ استعلام نسبٍ لاحق بكلفةٍ لا تُذكر على الإدراج.
create index if not exists waitlist_entries_restored_from_idx
  on public.waitlist_entries (restored_from)
  where restored_from is not null;

-- ═══════════════════════════════════════════════════════════════════
-- استرداد النسب القائم قبل أن يُقلَّم
-- ═══════════════════════════════════════════════════════════════════
-- كتابةٌ على عمودٍ وُلد فارغًا قبل لحظات — لا تمسّ صفًّا قائمًا في أيّ
-- حقلٍ يقرؤه أحد. وهي جوهر الخيار (ب): ما في queue_events اليوم يُنسخ
-- إلى مكانٍ لا يُقلَّم.

update public.waitlist_entries w
   set restored_from = (e.detail->>'restored_from')::uuid
  from public.queue_events e
 where e.kind = 'restored'
   and e.detail ? 'restored_from'
   and w.id = e.entry_id
   and w.restored_from is null;

-- تحقّقٌ بعديّ: العدد المستردّ يطابق ما في السجلّ تمامًا.
do $v$
declare v_expected int; v_got int;
begin
  select count(distinct e.entry_id) into v_expected
    from public.queue_events e
    join public.waitlist_entries w on w.id = e.entry_id
   where e.kind='restored' and e.detail ? 'restored_from';

  select count(*) into v_got
    from public.waitlist_entries where restored_from is not null;

  if v_got <> v_expected then
    raise exception 'استُرد % صفًّا والمتوقّع % — توقّف', v_got, v_expected;
  end if;
end $v$;

commit;

-- ═══════════════════════════════════════════════════════════════════
-- ما لم يُفعل — وهو نصف القرار
-- ═══════════════════════════════════════════════════════════════════
-- لم تُلمس أيّ حسبةٍ في التقارير. الضيف الذي أُرجع ما زال يُحتسب مرّتين
-- اليوم كما كان بالضبط (مرّةً ملغًى ومرّةً مخدومًا)، ولا رقمٌ معروضٌ
-- تغيّر. هذا مقصود: تصحيح العدّ يغيّر أربعة أرقامٍ رآها المالك
-- (خدمناهم ١٠٦→١٠٥ · انضموا ٢١٩→٢١٧ · ملغاة ١٠٨→١٠٧ · الانتظار ١٤٠→١٤١)،
-- وقرارُ ذلك له وحده.
--
-- وحين يُتّخذ، يصير سطرًا واحدًا: `where restored_from is null` — على
-- بياناتٍ محفوظةٍ لا مقلَّمة.
--
-- الرجوع:
--   drop index if exists public.waitlist_entries_restored_from_idx;
--   alter table public.waitlist_entries drop column if exists restored_from;
-- ولا كود يقرؤه، فلا شيء يُرجَع معه.
