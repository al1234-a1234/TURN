-- ════════════════════════════════════════════════════════════════════════════
--  الطابور لا يُصفَّر عند منتصف الليل
--
--  كان `set_waitlist_position` يحصر `max(position)` بصفوف **تاريخ الرياض
--  الحالي**. والمطعم السعوديّ النمطيّ يفتح ٦ مساءً ويغلق ٢ فجرًا — أي يعبر
--  منتصف الليل وطابوره حيّ. فعند ٠٠:٠٠ يتغيّر التاريخ، فتخرج صفوف ما قبل
--  منتصف الليل من حساب الحدّ الأقصى، ويبدأ الترقيم من ١ من جديد.
--
--  الأثر مقيسٌ لا مُستنتَج (فرع الكناري، معاملةٌ مُتراجَعٌ عنها):
--
--    الضيف        انضمّ    الترتيب المُسنَد   تذكرته تقول
--    ضيف-٢٣٥٠     23:50    ٤٠                أمامك ١ · ترتيبك ٢
--    ضيف-٠٠١١     00:11    ١                 أمامك ٠ · ترتيبك ١
--
--  فالوافد بعد منتصف الليل يتصدّر الطابور، ومن ينتظر منذ ٢٣:٥٠ يهبط خلفه.
--  و`waitlist_ticket_status` تحسب «أمامك» بعدّ الصفوف الحيّة الأقلّ ترتيبًا،
--  فالرقم الخاطئ يصل الضيف مباشرةً على شاشته.
--
--  وهذا أسوأ أنواع الأعطال: لا خطأ، لا تحذير، رقمٌ معقولٌ وكاذب — يظهر مرّةً
--  كلّ ليلة، في الساعة التي يكون فيها المطعم أكثر ما يكون امتلاءً.
--
--  ⚠ وما ليس عطبًا — فُحص قبل الإصلاح: `expire_stale_waitlist` **لا** تُنهي
--  صفوفًا حيّة عند منتصف الليل. قاعدتها زمنٌ منقضٍ لا تاريخ: ٨ ساعات، أو ٤٥
--  دقيقة والفرع مغلق. الضيفان أعلاه بقيا `waiting` كلاهما عند ٠٠:١١.
--  فالخلل في الترقيم وحده، والإصلاح يقتصر عليه.
--
--  العلاج: يُحذف شرط التاريخ، ويصير الحدّ الأقصى على **الطابور الحيّ** كلّه.
--  الترتيب يتبع ترتيب الوصول (`joined_at`) لأنّ الصفوف تُدخَل بترتيب وصولها،
--  ولا يقفز أحدٌ على أحد. وحين يفرغ الطابور تمامًا يعود الترقيم إلى ١ من
--  تلقائه — عند الفراغ لا عند الساعة، وهذا هو الصواب.
--
--  ومكسبٌ جانبيّ: الشرط المحذوف كان مُرشِّحًا بقيًّا فوق فهرس
--  `idx_waitlist_active (branch_id, position) WHERE status in (…)`. بحذفه
--  صار الاستعلام مطابقًا للفهرس تمامًا، والقفل الاستشاريّ يُمسَك زمنًا أقصر.
-- ════════════════════════════════════════════════════════════════════════════

create or replace function public.set_waitlist_position()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if new.position is null then
    -- يمنع تكرار الرقم عند انضمامين متزامنين لنفس الفرع. المفتاح من
    -- branch_id وحده، فلا تتسلسل الفروع خلف قفلٍ واحد.
    perform pg_advisory_xact_lock(hashtext(new.branch_id::text));

    -- الطابور الحيّ كلّه، بلا حصرٍ بيومٍ تقويميّ — فمن انتظر قبل منتصف
    -- الليل يبقى أمام من جاء بعده.
    select coalesce(max(w.position), 0) + 1
      into new.position
      from public.waitlist_entries w
     where w.branch_id = new.branch_id
       and w.status in ('waiting', 'notified');
  end if;
  return new;
end;
$function$;
