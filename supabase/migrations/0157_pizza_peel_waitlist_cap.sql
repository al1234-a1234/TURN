-- ============================================================================
--  سقف طابور Pizza peel — 3 اليوم، والمطعم يطلق بستاند باركود.
--
--  ⛔ غير مطبَّق. **الرقم أدناه عيّنة placeholder لا قرار** — ينتظر أن يحدّده
--  المالك، ثمّ يُستبدل الرقم ويُطبَّق.
--
--  ── المقارنة ──
--    Eficto       max_waitlist_size = 50
--    Pizza peel   max_waitlist_size = 3   ← الفرع النشِط الوحيد
--
--  ── لماذا يستحقّ توقّفًا لا رقمًا أخترعه ──
--  المطعم يطلق بستاند باركود: العميل الرابع الذي يمسح يرى «الطابور ممتلئ
--  حاليًا» (P0010) من اللحظة الأولى — لا سببٌ تشغيليٌّ ظاهر (مطبخٌ صغير؟
--  افتتاحٌ تجريبيّ؟ رقمٌ أُدخل تجربةً ولم يُراجَع؟)، والفرق بين هذه
--  الاحتمالات قرار مالكٍ لا قرار كودٍ. سقفٌ خاطئ في الاتّجاهين يضرّ: أضيق
--  ممّا يحتمله المطعم فعلًا يخسر عملاءً يوم الإطلاق، وأوسع ممّا يحتمله
--  يُغرق مطبخًا لم يُختبر بعد.
--
--  الحالة الآن: queue_paused = true لكلا الفرعين (الطابور مغلقٌ حتى يفتحه
--  الاستقبال، 0150) — فالسقف الخاطئ لا يؤذي أحدًا هذه اللحظة، لكنّه سيؤذي
--  فور فتح الطابور يوم الإطلاق نفسه إن بقي 3 دون قصد.
-- ============================================================================

update public.branch_settings
   set max_waitlist_size = /* ضع الرقم الذي يحدّده المالك هنا */ null
 where branch_id = (
   select b.id from public.branches b
     join public.restaurants r on r.id = b.restaurant_id
    where r.slug = 'pizza-peel' and b.is_active
 );

