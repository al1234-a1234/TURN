--  حارس: لا رمزَ رفضٍ جديدٍ في الانضمام بلا رسالةٍ تقابله في الواجهة.
--
--  ⛔ غير مطبَّق. ينتظر إذن المالك الصريح (ترحيل).
--
--  ── العطب الذي وُلد منه ──
--  `join_waitlist_guest` ترفع سبعة رموز. والإجراء في الواجهة كان يعالج خمسة،
--  فيسقط P0011 (الطابور موقوف — وهو افتراضُ كلّ فرعٍ جديدٍ منذ 0150) و22023
--  في «تعذّر الانضمام. حاول مرة أخرى». العميل واقفٌ على باب مطعمٍ الآن،
--  والجملة لا تقول له أيدخل أم ينتظر أم يمشي.
--
--  ولم يقع الخطأ في الترجمة بل في **التزامن**: أُضيف رمزٌ في القاعدة (0148)
--  ولم يُضَف نصُّه في الواجهة، ولا شيء ربط بينهما. هذا الفحص هو الرابط.
--
--  ── ما يفعله ──
--  يستخرج رموز `errcode` من نصّ الدالّة ويقارنها بقائمةٍ مجمّدة. فأيّ رمزٍ
--  جديدٍ يُضاف في ترحيلٍ قادمٍ **يُسقط الفحص اليوميّ فورًا**، فيُذكِّر كاتبَه
--  أن يضيف نصَّه في `src/lib/join-errors.ts` ثمّ يوسّع هذه القائمة عمدًا.
--
--  والقائمة تُوسَّع بقرارٍ مكتوب لا بصمت — وهذا هو الغرض كلّه.
--
--  ── ولماذا مجمَّدة لا محسوبة ──
--  فحصٌ يقارن الدالّة بنفسها أخضرُ دائمًا. القيمة كلّها في أنّ الطرف الآخر
--  من المقارنة **ثابتٌ يقرؤه إنسان**، فيُجبر التغييرَ أن يمرّ به.
--
--  الحالة عند الكتابة: 22023 · P0001 · P0002 · P0003 · P0010 · P0011 · P0429
-- ============================================================================

do $mig$
declare v_def text;
begin
  select pg_get_functiondef(p.oid) into v_def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname='public' and p.proname='run_critical_checks';
  if v_def is null then raise exception 'run_critical_checks غير موجودة'; end if;

  if position('w30_join_codes_frozen' in v_def) = 0 then
    v_def := replace(v_def, E'    (\'q20_schema_no_drift\',',
      E'    (\'w30_join_codes_frozen\', (\n'
   || E'        select coalesce(array_agg(distinct m[1] order by m[1]), \'{}\')\n'
   || E'             = array[\'22023\',\'P0001\',\'P0002\',\'P0003\',\'P0010\',\'P0011\',\'P0429\']\n'
   || E'          from pg_proc p2\n'
   || E'          join pg_namespace n2 on n2.oid = p2.pronamespace,\n'
   || E'          lateral regexp_matches(pg_get_functiondef(p2.oid),\n'
   || E'                                 \'errcode\\s*=\\s*\'\'([A-Z0-9]+)\'\'\', \'g\') m\n'
   || E'         where n2.nspname = \'public\' and p2.proname = \'join_waitlist_guest\')),\n'
   || E'    (\'q20_schema_no_drift\',');
  end if;

  execute v_def;
end
$mig$;

