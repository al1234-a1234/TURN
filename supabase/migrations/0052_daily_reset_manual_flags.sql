-- مصيدة النسيان: «أغلق الفرع الآن» و«مزدحم الآن» أزرار لحظة تشغيلية،
-- لكنهما كانا يبقيان للأبد — استقبالٌ أغلق يدويًّا آخر الليل ونسي، يصحو
-- الفرع «مغلقًا» طوال اليوم التالي والعملاء يروحون لغيره والملامة على
-- المنصّة. تصفير يومي فجرًا (٤ فجرًا بتوقيت الرياض = ٠١:٠٠ UTC، بعد إقفال
-- حتى أطول سهرة): كل يوم يبدأ نظيفًا، وأوقات الدوام المضبوطة تبقى هي
-- المتحكم الدائم (لا تُمسّ هنا).
select cron.schedule(
  'reset-manual-flags',
  '0 1 * * *',
  $$ update public.branch_settings
        set manually_closed = false, busy_now = false
      where manually_closed or busy_now $$
);
